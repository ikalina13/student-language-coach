export function icon(name) {
  return h('span', { 'aria-hidden': 'true', style: { display: 'inline-flex' }, html:
    `<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" width="19" height="19">${paths[name] || ''}</svg>` });
}

export function toast(message) {
  const t = h('div.toast', { role: 'status' }, message);
  document.body.append(t);
  setTimeout(() => t.remove(), 2200);
}

export const levelTag = (id, label) => h(`span.lvl.${id}`, label);
