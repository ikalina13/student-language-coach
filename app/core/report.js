// Builds the one-page printable report card. Turned into a PDF by main.js.
const CAT = { school: 'School', family: 'Family', food: 'Food', animals: 'Animals', places: 'Places', feelings: 'Feelings', actions: 'Actions', common: 'Common Words' };
const LVL = { beginner: 'Beginner', intermediate: 'Intermediate', advanced: 'Advanced' };

const esc = (s) => String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const pct = (a, b) => (b ? Math.round((a / b) * 100) : 0);
const fmtDate = (d) => new Date(d).toLocaleDateString('en-PH', { year: 'numeric', month: 'long', day: 'numeric' });

function bar(label, { learned, total }) {
  return `<tr><td>${esc(label)}</td><td class="num">${learned} / ${total}</td>
    <td class="barcell"><div class="bar"><span style="width:${pct(learned, total)}%"></span></div></td></tr>`;
}

function renderReportHTML({ user, stats, date }) {
  const quizRows = stats.recentQuizzes.length
    ? stats.recentQuizzes.map((q) => `<tr><td>${fmtDate(q.date)}</td><td>${esc(CAT[q.category] || q.category)}</td>
        <td>${esc(LVL[q.level] || q.level)}</td><td class="num">${q.score}/${q.total}</td><td class="num">${q.percent}%</td></tr>`).join('')
    : '<tr><td colspan="5" class="empty">No quizzes taken yet</td></tr>';

  return `<!DOCTYPE html><html><head><meta charset="utf-8"><title>Student Language Coach Report</title><style>
  @page { size: A4; margin: 18mm 16mm; }
  * { box-sizing: border-box; }
  body { font-family: "Segoe UI", system-ui, sans-serif; color: #14213d; font-size: 11pt; margin: 0; }
  header { display: flex; justify-content: space-between; align-items: flex-end; border-bottom: 2px solid #1d4ed8; padding-bottom: 10px; }
  .brand { font-size: 22pt; font-weight: 700; color: #1d4ed8; letter-spacing: -0.5px; }
  .brand small { display: block; font-size: 9.5pt; font-weight: 500; color: #5b6b8c; letter-spacing: 0; }
  .who { text-align: right; } .who b { font-size: 13pt; display: block; } .who span { color: #5b6b8c; font-size: 10pt; }
  h2 { font-size: 13pt; color: #14213d; margin: 22px 0 8px; }
  .tiles { display: grid; grid-template-columns: repeat(4, 1fr); gap: 10px; }
  .tile { border: 1px solid #d6deeb; border-radius: 8px; padding: 10px 12px; }
  .tile b { font-size: 18pt; display: block; } .tile span { color: #5b6b8c; font-size: 9.5pt; }
  table { width: 100%; border-collapse: collapse; font-size: 10pt; }
  td, th { padding: 5px 6px; border-bottom: 1px solid #e5eaf2; text-align: left; }
  th { color: #5b6b8c; font-weight: 600; font-size: 9.5pt; }
  .num { text-align: right; white-space: nowrap; } .barcell { width: 45%; }
  .bar { height: 8px; background: #e5eaf2; border-radius: 4px; overflow: hidden; } .bar span { display: block; height: 100%; background: #1d4ed8; }
  .cols { display: grid; grid-template-columns: 1fr 1fr; gap: 20px; }
  .empty { color: #5b6b8c; text-align: center; padding: 14px; }
  footer { margin-top: 26px; color: #5b6b8c; font-size: 9pt; display: flex; justify-content: space-between; }
  </style></head><body>
  <header>
    <div class="brand">Student Language Coach<small>English Vocabulary Progress Report</small></div>
    <div class="who"><b>${esc(user.displayName)}</b><span>Grade ${esc(user.grade)}, @${esc(user.username)}<br>${fmtDate(date)}</span></div>
  </header>
  <h2>Summary</h2>
  <div class="tiles">
    <div class="tile"><b>${stats.wordsLearned}</b><span>of ${stats.totalWords} words learned</span></div>
    <div class="tile"><b>${stats.storiesCompleted}</b><span>of ${stats.totalStories} stories completed</span></div>
    <div class="tile"><b>${stats.quizzesTaken}</b><span>quizzes completed</span></div>
    <div class="tile"><b>${stats.sentencesDone}</b><span>of ${stats.totalSentences} sentences practiced</span></div>
  </div>
  <div class="tiles" style="grid-template-columns:1fr 1fr;margin-top:10px">
    <div class="tile"><b>${stats.averageScore}%</b><span>average quiz score</span></div>
    <div class="tile"><b>${stats.bestScore}%</b><span>best quiz score</span></div>
  </div>
  <div class="cols">
    <div><h2>Words by category</h2><table>${Object.entries(stats.byCategory).map(([k, v]) => bar(CAT[k] || k, v)).join('')}</table></div>
    <div><h2>Words by level</h2><table>${Object.entries(stats.byLevel).map(([k, v]) => bar(LVL[k] || k, v)).join('')}</table></div>
  </div>
  <h2>Recent quizzes</h2>
  <table><tr><th>Date</th><th>Category</th><th>Level</th><th class="num">Score</th><th class="num">%</th></tr>${quizRows}</table>
  <footer><span>Generated by Student Language Coach</span><span>Signature: ______________________</span></footer>
  </body></html>`;
}

module.exports = { renderReportHTML };
